"""Builds a ROM: compiles the C program and packs it with the textures and sounds.

    python tools/build.py                     build/sulphur.v32 from src/main.c
    python tools/build.py tests/tests.c out   build/out.v32 from another program (tests)

Textures and sounds come from the asset groups (tools/assetlib.py): assets/<group>/rom.txt, joined
in the order of assetlib.GROUPS. src/gen/rom.h gets the first texture and sound id of every group.
"""
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from assetlib import GROUPS, _atomic_write  # noqa: E402
from toolchain import ROOT, tools  # noqa: E402

BUILD = ROOT / "build"


def run(cmd):
    result = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    out = (result.stdout + result.stderr).strip()
    # the compiler warns about unused variables; anything else is worth reading
    lines = [l for l in out.splitlines() if l and "is not used" not in l]
    if result.returncode != 0:
        sys.exit("\n".join(lines) or f"failed: {cmd}")
    for l in lines:
        if "warning" in l or "error" in l:
            print(l)


def assets():
    """Textures and sounds of all groups in ROM order; writes src/gen/rom.h."""
    textures, sounds = [], []
    header = ["// generated by tools/build.py: first texture and sound id of each asset group",
              "#ifndef GEN_ROM_H", "#define GEN_ROM_H"]
    for group in GROUPS:
        up = group.upper()
        header.append(f"#define TEX_BASE_{up} {len(textures)}")
        header.append(f"#define SND_BASE_{up} {len(sounds)}")
        rom = ROOT / "assets" / group / "rom.txt"
        if not rom.exists():
            continue
        for line in rom.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            kind, path = line.split(None, 1)
            (textures if kind == "texture" else sounds).append(ROOT / path)
    header += ["#endif", ""]
    target = ROOT / "src/gen/rom.h"
    text = "\n".join(header)
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        _atomic_write(target, text)
    return textures, sounds


def convert(t, src, kind):
    """png -> vtex, wav -> vsnd, cached by modification time under build/assets."""
    out = BUILD / "assets" / src.relative_to(ROOT).with_suffix(".vtex" if kind == "texture" else ".vsnd")
    if out.exists() and out.stat().st_mtime >= src.stat().st_mtime:
        return out
    out.parent.mkdir(parents=True, exist_ok=True)
    run([t["png2vircon" if kind == "texture" else "wav2vircon"], src, "-o", out])
    return out


def build(program="src/main.c", name="sulphur"):
    t = tools()
    BUILD.mkdir(exist_ok=True)
    obj = BUILD / "obj"
    obj.mkdir(exist_ok=True)
    asm, vbin = obj / f"{name}.asm", obj / f"{name}.vbin"
    textures, sounds = assets()
    run([t["compile"], ROOT / program, "-o", asm])
    run([t["assemble"], asm, "-o", vbin])
    xml = [
        '<?xml version="1.0" encoding="UTF-8" ?>',
        '<rom-definition version="1.0">',
        f'    <rom type="cartridge" title="Sulphur" version="1.0" />',
        f'    <binary path="{vbin.as_posix()}" />',
        "    <textures>",
        *[f'        <texture path="{convert(t, p, "texture").as_posix()}" />' for p in textures],
        "    </textures>",
        "    <sounds>",
        *[f'        <sound path="{convert(t, p, "sound").as_posix()}" />' for p in sounds],
        "    </sounds>",
        "</rom-definition>",
    ]
    definition = obj / f"{name}.xml"
    definition.write_text("\n".join(xml) + "\n", encoding="utf-8")
    rom = BUILD / f"{name}.v32"
    run([t["packrom"], definition, "-o", rom])
    return rom


if __name__ == "__main__":
    args = sys.argv[1:]
    print(build(*args) if args else build())
