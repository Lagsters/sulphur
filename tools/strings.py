def main():
    lines = ["// generated by tools/strings.py: do not edit", "#ifndef GEN_STRINGS_H", "#define GEN_STRINGS_H", ""]
    for i, (name, en, pl) in enumerate(STRINGS):
        lines.append(f"#define STR_{name} {i}")
    lines.append(f"#define STR_COUNT {len(STRINGS)}")
    lines.append("")
    for name, en, pl in STRINGS:
        lines.append(f"int[ {len(en) + 1} ] str_en_{name.lower()} = {c_string(en)};")
        lines.append(f"int[ {len(pl) + 1} ] str_pl_{name.lower()} = {c_string(pl)};")
    lines += ["", "int*[ STR_COUNT ] str_en;", "int*[ STR_COUNT ] str_pl;", "", "void init_strings()", "{"]
    for name, en, pl in STRINGS:
        lines.append(f"    str_en[ STR_{name} ] = str_en_{name.lower()}; str_pl[ STR_{name} ] = str_pl_{name.lower()};")
    lines += ["}", "", "// the text in the chosen language (lang in state.h)",
              "int* tr( int id )", "{", "    if( lang == 1 ) return str_pl[ id ];", "    return str_en[ id ];", "}",
              "", "#endif", ""]
    _atomic_write(ROOT / "src/gen/strings.h", "\n".join(lines))


if __name__ == "__main__":
    main()
